المادة السابعة: وفاة أحد الشركاء
في حال وفاة أحد الشركاء - لا قدّر الله - تنتقل حصته في العقار إلى ورثته الشرعيين وفق أحكام الفرائض الشرعية والأنظمة السعودية النافذة، ولا يُخل هذا العقد بحقوقهم الشرعية بأي حال. وتسري على ورثة الشريك المتوفى جميع أحكام هذا العقد فيما يخص الحصة الموروثة.
مع ذلك، وحفاظًا على استمرارية إدارة العقار، يكون لباقي الشركاء - مجتمعين أو منفردين - حق أولوية في شراء الحصة الموروثة من الورثة، بسعر عادل يُحدَّد باتفاق الطرفين، أو بواسطة مُقيَّمين عقاريين مرخّصين (اثنين على الأقل) يُختار كل منهما من أحد الطرفين، ويُعتمد متوسط تقييمهما، وذلك خلال مدة أقصاها سنة واحدة من تاريخ استخراج صك حصر الورثة. ولا يُلزم هذا البند الورثة بالبيع، وإنما يمنح باقي الشركاء أولوية الشراء متى رغب الورثة في التصرف بالحصة الموروثة أو جزء منها.
تستمر إدارة العقار خلال هذه الفترة وفق ما هو متفق عليه في هذا العقد، ويحل الورثة (أو من يمثلهم نظامًا) محل مورثهم في استلام العائد المستحق لحصته إلى حين تسوية الأمر.

