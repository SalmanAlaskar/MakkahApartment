-- Partnership contract: a single versioned document (like property_settings/app_credentials)
-- plus one signature row per partner per version. Editing the contract bumps the version and
-- creates fresh pending signature rows for that version, so a "signed" status always corresponds
-- to the exact text that was signed -- never to a version that was silently edited afterward.
create table if not exists partnership_contract (
  id boolean primary key default true,
  content text not null,
  version integer not null default 1,
  updated_at timestamptz not null default now(),
  constraint partnership_contract_singleton check (id)
);

alter table partnership_contract enable row level security;

create table if not exists contract_signatures (
  id uuid primary key default gen_random_uuid(),
  partner_id uuid not null references partners(id) on delete cascade,
  contract_version integer not null,
  sign_token uuid not null default gen_random_uuid(),
  signer_name text,
  national_id text,
  signature_data text,
  signed_at timestamptz,
  ip_address text,
  created_at timestamptz not null default now(),
  unique (partner_id, contract_version),
  unique (sign_token)
);

alter table contract_signatures enable row level security;

create index if not exists idx_contract_signatures_token on contract_signatures(sign_token);

