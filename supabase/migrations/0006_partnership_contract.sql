- تحصيل الإيجارات ودفع المصاريف التشغيلية (كعمولة التشغيل، والنظافة والصيانة، والفواتير الشهرية).
- الاحتفاظ بسجل دقيق لجميع الحجوزات والإيرادات والمصروفات، عبر نظام إلكتروني لإدارة الممتلكات يُطّلع عليه جميع الشركاء متى شاؤوا.
- توزيع صافي العائد على الشركاء بنسبة حصة كل منهم، بعد خصم عمولة التشغيل والمصاريف.
يبقى الشريك المدير مسؤولًا أمام باقي الشركاء عن حسن إدارته، وعليه تقديم كشف حساب دوري متى طُلب منه ذلك. لا يجوز للشريك المدير التصرف في العقار ذاته (كبيعه أو رهنه) دون موافقة كتابية من جميع الشركاء.

المادة الرابعة: توزيع العائد والمصاريف
